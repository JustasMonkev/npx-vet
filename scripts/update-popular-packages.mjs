// Regenerates src/data/popularPackages.ts from the npm-high-impact package,
// which tracks the most downloaded and most depended-upon packages on npm.
// Usage: node scripts/update-popular-packages.mjs
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import pacote from "pacote";

const PACKAGE_COUNT = 5000;
const OUTPUT_PATH = new URL("../src/data/popularPackages.ts", import.meta.url);

const extractDir = await mkdtemp(join(tmpdir(), "npm-high-impact-"));
try {
  const { version } = await pacote.manifest("npm-high-impact@latest");
  await pacote.extract(`npm-high-impact@${version}`, extractDir);
  const { npmHighImpact } = await import(pathToFileURL(join(extractDir, "index.js")).href);
  const names = [...new Set(npmHighImpact)].slice(0, PACKAGE_COUNT);

  const header = [
    "// Generated by scripts/update-popular-packages.mjs. Do not edit by hand.",
    `// Source: npm-high-impact@${version}, top ${names.length} package names by download and dependent impact.`
  ];
  const body = names.map((name) => `  ${JSON.stringify(name)}`).join(",\n");
  await mkdir(new URL(".", OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, `${header.join("\n")}\nexport const POPULAR_PACKAGES: readonly string[] = [\n${body}\n];\n`);
  process.stdout.write(`Wrote ${names.length} package names from npm-high-impact@${version}\n`);
} finally {
  await rm(extractDir, { recursive: true, force: true });
}
